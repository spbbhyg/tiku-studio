def classify(text: str) -> str:
    """返回最可能的专题名；都不命中时返回空串。"""
    t = (text or "")[:4000]
    best, score = "", 0
    for pat, topic, w in RULES:
        hits = len(re.findall(pat, t))
        if not hits:
            continue
        s = hits * w
        if s > score:
            best, score = topic, s
    return best


def classify_batch(texts: list[str]) -> list[str]:
    return [classify(t) for t in texts]
